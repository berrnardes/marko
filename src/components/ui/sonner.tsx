"use client"

import {
  CircleCheckIcon,
  InfoIcon,
  Loader2Icon,
  OctagonXIcon,
  TriangleAlertIcon,
} from "lucide-react"
import { Toaster as Sonner, type ToasterProps } from "sonner"

// The CRM shell owns a manual light/dark toggle and passes the resolved theme
// in, so this primitive needs no theme-provider dependency. Toasts render in a
// body-level portal (outside the `.app-theme` token scope), so we let sonner's
// own light/dark palette — driven by the `theme` prop — color the surface
// rather than inheriting app CSS variables that would resolve to the wrong
// scope.
const Toaster = ({ theme = "system", ...props }: ToasterProps) => {
  return (
    <Sonner
      theme={theme}
      className="toaster group"
      icons={{
        success: <CircleCheckIcon className="size-4" />,
        info: <InfoIcon className="size-4" />,
        warning: <TriangleAlertIcon className="size-4" />,
        error: <OctagonXIcon className="size-4" />,
        loading: <Loader2Icon className="size-4 animate-spin" />,
      }}
      {...props}
    />
  )
}

export { Toaster }
